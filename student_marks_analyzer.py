marks = [75, 33, 85, 98, 56]


def analyze_marks(marks):

    if len(marks) == 0:
        print("No marks available to analyze.")
        return

    total = 0
    highest = marks[0]
    lowest = marks[0]

    # Calculate total, highest and lowest marks
    for r in marks:
        total += r

        if r > highest:
            highest = r

        if r < lowest:
            lowest = r

    # Calculate average and percentage
    avg = total / len(marks)
    percentage = total / (len(marks) * 100) * 100

    # Determine grade
    if percentage >= 90:
        grade = "A"
    elif percentage >= 80:
        grade = "B"
    elif percentage >= 70:
        grade = "C"
    elif percentage >= 60:
        grade = "D"
    elif percentage >= 50:
        grade = "E"
    else:
        grade = "Fail"

    print("Total Marks:", total)
    print("Highest Marks:", highest)
    print("Lowest Marks:", lowest)
    print("Average Marks:", avg)
    print("Percentage: {:.2f}%".format(percentage))
    print("Final Grade:", grade)

analyze_marks(marks)

